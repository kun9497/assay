// D103: pnpm-lock.yaml and yarn berry's yarn.lock are read now, not refused.
// This section drives that through Parse first, per CLAUDE.md's "the helper
// is covered; nothing calls it" - the fixtures below exercise pnpmlock.Parse
// and the berry half of yarnlock.Parse directly too (pnpmlock_test.go,
// yarnlock/berry_test.go), but nothing there can catch dirscan's own dispatch
// falling back to the old refusal, or losing the local/git/malformed skip
// classification on the way through relocate(). Deleting either KindPnpmLock
// or the berry branch of the KindYarnLock arm must turn every assertion below
// red: packages vanish, Unread reappears, or the skip disclosure goes silent.

const pnpmCallerFixture = `lockfileVersion: '9.0'

packages:

  widget-core@2.4.6:
    resolution: {integrity: sha512-deadbeefdeadbeefdeadbeefdeadbeefdeadbeef==}

  '@scope-fixture/workspace-thing@0.0.0-use.local':
    resolution: {directory: packages/workspace-thing, type: directory}

  forked-dep@0.0.0:
    resolution: {type: git, repo: 'https://github.com/acme-org/forked-dep', commit: 9f3ab12deadbeef}
`

func TestParse_PnpmLockReachesTheDispatch(t *testing.T) {
	root := writeTree(t, map[string]string{"pnpm-lock.yaml": pnpmCallerFixture})

	target, stats, found, err := Parse(root)
	if err != nil {
		t.Fatalf("Parse: %v", err)
	}
	// The old refusal is gone: before D103 this same tree produced one
	// Unread entry and zero packages.
	if len(found.Unread) != 0 {
		t.Fatalf("Unread = %+v, want none — pnpm-lock.yaml is read now", found.Unread)
	}
	if len(found.Read) != 1 || found.Read[0].Kind != KindPnpmLock {
		t.Fatalf("Read = %+v, want one KindPnpmLock entry", found.Read)
	}

	var got []string
	for _, p := range target.Packages {
		got = append(got, p.Name)
		if p.Name != "widget-core" {
			continue
		}
		if p.Version != "2.4.6" {
			t.Errorf("widget-core version = %q, want 2.4.6", p.Version)
		}
		if len(p.Locations) != 1 || p.Locations[0].Path != "pnpm-lock.yaml" {
			t.Errorf("widget-core locations = %+v, want [pnpm-lock.yaml]", p.Locations)
		}
		if p.Ecosystem != "npm" {
			t.Errorf("widget-core ecosystem = %q, want npm", p.Ecosystem)
		}
	}
	if len(target.Packages) != 1 {
		t.Fatalf("packages = %v, want widget-core alone (the workspace member and the git "+
			"dependency are not registry packages)", got)
	}

	// The local and git entries must both be visible — named, with why — even
	// though only the git one is a genuine coverage gap.
	byLine := map[string]string{}
	for _, u := range found.Unusable {
		if u.Path != "pnpm-lock.yaml" {
			t.Errorf("Unusable path = %q, want pnpm-lock.yaml", u.Path)
		}
		byLine[u.Line] = u.Reason
	}
	if _, ok := byLine["@scope-fixture/workspace-thing@0.0.0-use.local"]; !ok {
		t.Errorf("Unusable = %+v, want the workspace member named", found.Unusable)
	}
	if _, ok := byLine["forked-dep@0.0.0"]; !ok {
		t.Errorf("Unusable = %+v, want the git dependency named", found.Unusable)
	}

	// Only the git skip is a real coverage gap (SkippedNoVersion): the
	// workspace member must not inflate Stats at all, which is what keeps it
	// out of the target-incompleteness gate (D103's local/git/malformed
	// split).
	if stats.Components != 2 {
		t.Errorf("Components = %d, want 2 (widget-core cataloged, forked-dep skipped; "+
			"the workspace member is not a component)", stats.Components)
	}
	if stats.Cataloged != 1 {
		t.Errorf("Cataloged = %d, want 1", stats.Cataloged)
	}
	if stats.SkippedNoVersion != 1 {
		t.Errorf("SkippedNoVersion = %d, want 1 (the git dependency)", stats.SkippedNoVersion)
	}
}

