// A pnpm lockfile assay genuinely cannot read - not "recognized and
// deferred" any more, but really malformed - must still fail the scan.
// D11's untrustworthy-result ranking did not change; only which files earn
// it did.
func TestParse_MalformedPnpmLockStillFailsTheScan(t *testing.T) {
	root := writeTree(t, map[string]string{
		"pnpm-lock.yaml": "lockfileVersion: v6\n\npackages:\n  left-pad@1.3.0:\n    resolution: {integrity: sha512-x}\n",
	})

	target, _, found, err := Parse(root)
	if err != nil {
		t.Fatalf("Parse: %v", err)
	}
	if len(target.Packages) != 0 {
		t.Errorf("packages = %+v, want none", target.Packages)
	}
	if len(found.Unread) != 1 || !found.Unread[0].Failed {
		t.Fatalf("Unread = %+v, want exactly one Failed entry", found.Unread)
	}
	if !strings.Contains(found.Unread[0].Reason, "lockfileVersion") {
		t.Errorf("Unread reason = %q, want it to name the bad lockfileVersion", found.Unread[0].Reason)
	}
	if !found.AnyFailed() {
		t.Error("AnyFailed() = false, want true")
	}
}

