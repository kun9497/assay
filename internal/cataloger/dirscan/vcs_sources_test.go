package dirscan

import (
	"testing"
)

// A git, URL or path dependency carries the version its own checkout declares,
// which need not be any registry release an advisory names: the fork can sit
// at "4.17.20" with the fix missing (a false negative once the version is
// read as fixed) or carry it (a false positive). pnpm, yarn berry, gemlock and
// pipfilelock already refuse that shape; these rows hold the other five
// lockfile readers to the same refusal (audit 2026-10-22 P4).
//
// Driven through Parse, not the parsers, per CLAUDE.md's "The helper is
// covered; nothing calls it": each row's assertions differ when the check is
// gone (the fork is cataloged, the counter does not move, the disclosure is
// silent) and when dirscan stops passing the parser's skips on.
//
// One row per check, so that disabling any single one of them turns exactly
// its own row red: the yarn v1 key-spec row resolves to an https codeload
// tarball, and the resolved rows keep a registry-shaped spec, so neither is
// caught by the other's check.
//
// Names are chosen so no assertion can pass on a neighbouring field:
// "sturdy-registry-pkg" and "forked-vcs-pkg" share no substring that is
// either's whole name.
func TestParse_NonRegistrySourcesAreSkippedAndNamed(t *testing.T) {
	const gitRef = "0123456789abcdef0123456789abcdef01234567"

	rows := []struct {
		name string
		file string
		body string
		// skipped is the Unusable line the refused entry must be named by.
		skipped string
		// counted is whether the refusal is a coverage gap (SkippedNoVersion),
		// or a source this checkout itself holds, which is shown and not
		// counted - pnpm's causeLocal and berry's isLocalProtocol (D103).
		counted bool
	}{
		{
			name: "npm v3 resolved git+ssh",
			file: "package-lock.json",
			body: `{"name":"root-app","lockfileVersion":3,"packages":{
  "":{"name":"root-app","version":"1.0.0"},
  "node_modules/sturdy-registry-pkg":{"version":"2.3.4","resolved":"https://registry.npmjs.org/sturdy-registry-pkg/-/sturdy-registry-pkg-2.3.4.tgz","integrity":"sha512-aaaa"},
  "node_modules/forked-vcs-pkg":{"version":"4.17.20","resolved":"git+ssh://git@github.com/someone/forked-vcs-pkg.git#` + gitRef + `"}
}}`,
			skipped: "forked-vcs-pkg",
			counted: true,
		},
		{
			name: "npm v3 resolved file: tarball",
			file: "package-lock.json",
			body: `{"name":"root-app","lockfileVersion":3,"packages":{
  "":{"name":"root-app","version":"1.0.0"},
  "node_modules/sturdy-registry-pkg":{"version":"2.3.4","resolved":"https://npm.internal.example/sturdy-registry-pkg/-/sturdy-registry-pkg-2.3.4.tgz","integrity":"sha512-aaaa"},
  "node_modules/forked-vcs-pkg":{"version":"4.17.20","resolved":"file:vendor/forked-vcs-pkg-4.17.20.tgz"}
}}`,
			skipped: "forked-vcs-pkg",
			// Counted, as npmlock already counts a "link": true entry: the
			// same local shape, and the same reader's existing answer.
			counted: true,
		},
		{
			name: "npm v1 git version",
			file: "package-lock.json",
			body: `{"lockfileVersion":1,"dependencies":{
  "sturdy-registry-pkg":{"version":"2.3.4","resolved":"https://registry.npmjs.org/sturdy-registry-pkg/-/sturdy-registry-pkg-2.3.4.tgz"},
  "forked-vcs-pkg":{"version":"git+https://github.com/someone/forked-vcs-pkg.git#` + gitRef + `"}
}}`,
			skipped: "forked-vcs-pkg",
			counted: true,
		},
		{
			name: "npm v1 github: shorthand version",
			file: "package-lock.json",
			body: `{"lockfileVersion":1,"dependencies":{
  "sturdy-registry-pkg":{"version":"2.3.4"},
  "forked-vcs-pkg":{"version":"github:someone/forked-vcs-pkg#` + gitRef + `","from":"github:someone/forked-vcs-pkg"}
}}`,
			skipped: "forked-vcs-pkg",
			counted: true,
		},
		{
			name: "npm v1 git resolved under a semver version",
			file: "package-lock.json",
			body: `{"lockfileVersion":1,"dependencies":{
  "sturdy-registry-pkg":{"version":"2.3.4","resolved":"https://registry.npmjs.org/sturdy-registry-pkg/-/sturdy-registry-pkg-2.3.4.tgz"},
  "forked-vcs-pkg":{"version":"4.17.20","resolved":"git+https://github.com/someone/forked-vcs-pkg.git#` + gitRef + `"}
}}`,
			skipped: "forked-vcs-pkg",
			counted: true,
		},
		{
			name: "yarn v1 github: key spec, codeload resolved",
			file: "yarn.lock",
			body: `# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.
# yarn lockfile v1


sturdy-registry-pkg@^2.3.0:
  version "2.3.4"
  resolved "https://registry.yarnpkg.com/sturdy-registry-pkg/-/sturdy-registry-pkg-2.3.4.tgz#aaaa"

"forked-vcs-pkg@github:someone/forked-vcs-pkg#` + gitRef + `":
  version "4.17.20"
  resolved "https://codeload.github.com/someone/forked-vcs-pkg/tar.gz/` + gitRef + `"
`,
			skipped: "forked-vcs-pkg",
			counted: true,
		},
		{
			name: "yarn v1 git resolved under a semver key (resolutions override)",
			file: "yarn.lock",
			body: `# yarn lockfile v1


sturdy-registry-pkg@^2.3.0:
  version "2.3.4"
  resolved "https://registry.yarnpkg.com/sturdy-registry-pkg/-/sturdy-registry-pkg-2.3.4.tgz#aaaa"

forked-vcs-pkg@^4.17.0:
  version "4.17.20"
  resolved "git+https://github.com/someone/forked-vcs-pkg.git#` + gitRef + `"
`,
			skipped: "forked-vcs-pkg",
			counted: true,
		},
		{
			name: "yarn v1 file: key spec",
			file: "yarn.lock",
			body: `# yarn lockfile v1


sturdy-registry-pkg@^2.3.0:
  version "2.3.4"
  resolved "https://registry.yarnpkg.com/sturdy-registry-pkg/-/sturdy-registry-pkg-2.3.4.tgz#aaaa"

"forked-vcs-pkg@file:../forked-vcs-pkg":
  version "4.17.20"
`,
			skipped: "forked-vcs-pkg",
			// Not counted, as berry does not count its file: entries: the
			// same filename, and the same answer for the same shape.
			counted: false,
		},
		{
			name: "Cargo.lock git+ source",
			file: "Cargo.lock",
			body: `version = 3

[[package]]
name = "sturdy-registry-pkg"
version = "2.3.4"
source = "registry+https://github.com/rust-lang/crates.io-index"
checksum = "aaaa"

[[package]]
name = "forked-vcs-pkg"
version = "0.10.40"
source = "git+https://github.com/someone/forked-vcs-pkg?branch=main#` + gitRef + `"
`,
			skipped: "forked-vcs-pkg",
			counted: true,
		},
		{
			name: "poetry.lock git source",
			file: "poetry.lock",
			body: `[[package]]
name = "sturdy-registry-pkg"
version = "2.3.4"
description = "a registry release"
optional = false
python-versions = ">=3.8"

[[package]]
name = "forked-vcs-pkg"
version = "3.2.0"
description = "a fork"
optional = false
python-versions = ">=3.8"
develop = false

[package.dependencies]
asgiref = ">=3.3.2"

[package.source]
type = "git"
url = "https://github.com/someone/forked-vcs-pkg.git"
reference = "main"
resolved_reference = "` + gitRef + `"

[metadata]
lock-version = "2.0"
`,
			skipped: "forked-vcs-pkg",
			counted: true,
		},
		{
			name: "poetry.lock directory source",
			file: "poetry.lock",
			body: `[[package]]
name = "sturdy-registry-pkg"
version = "2.3.4"

[[package]]
name = "forked-vcs-pkg"
version = "3.2.0"
develop = true

[package.source]
type = "directory"
url = "../forked-vcs-pkg"

[metadata]
lock-version = "2.0"
`,
			skipped: "forked-vcs-pkg",
			// Counted, as gemlock counts a PATH gem and pipfilelock a path
			// entry: poetry.lock never lists the project itself, so a
			// directory source here is always another checkout.
			counted: true,
		},
		{
			name: "uv.lock git source",
			file: "uv.lock",
			body: `version = 1
requires-python = ">=3.11"

[[package]]
name = "sturdy-registry-pkg"
version = "2.3.4"
source = { registry = "https://pypi.org/simple" }

[[package]]
name = "forked-vcs-pkg"
version = "3.2.0"
source = { git = "https://github.com/someone/forked-vcs-pkg?rev=main#` + gitRef + `" }
dependencies = [
    { name = "sturdy-registry-pkg" },
]
`,
			skipped: "forked-vcs-pkg",
			counted: true,
		},
		{
			name: "uv.lock path source",
			file: "uv.lock",
			body: `version = 1

[[package]]
name = "sturdy-registry-pkg"
version = "2.3.4"
source = { registry = "https://pypi.org/simple" }

[[package]]
name = "forked-vcs-pkg"
version = "3.2.0"
source = { path = "../vendor/forked_vcs_pkg-3.2.0.tar.gz" }
`,
			skipped: "forked-vcs-pkg",
			counted: true,
		},
		{
			name: "uv.lock editable source",
			file: "uv.lock",
			body: `version = 1

[[package]]
name = "sturdy-registry-pkg"
version = "2.3.4"
source = { registry = "https://pypi.org/simple" }

[[package]]
name = "forked-vcs-pkg"
version = "3.2.0"
source = { editable = "packages/forked-vcs-pkg" }
`,
			skipped: "forked-vcs-pkg",
			// Not counted: uv writes the project itself and every workspace
			// member as editable, so counting it would make every healthy uv
			// scan incomplete - the defect npmlock's root "" key once had.
			counted: false,
		},
	}

	for _, r := range rows {
		t.Run(r.name, func(t *testing.T) {
			root := writeTree(t, map[string]string{r.file: r.body})

			target, stats, found, err := Parse(root)
			if err != nil {
				t.Fatalf("Parse: %v", err)
			}
			for _, u := range found.Unread {
				t.Errorf("unexpected unread manifest %s: %s", u.Path, u.Reason)
			}

			var names []string
			for _, p := range target.Packages {
				names = append(names, p.Name+"@"+p.Version)
			}
			if len(target.Packages) != 1 || target.Packages[0].Name != "sturdy-registry-pkg" ||
				target.Packages[0].Version != "2.3.4" {
				t.Errorf("packages = %v, want sturdy-registry-pkg@2.3.4 alone - the fork's "+
					"self-declared version is not a registry release", names)
			}

			if len(found.Unusable) != 1 {
				t.Fatalf("Unusable = %+v, want exactly the refused entry, named", found.Unusable)
			}
			u := found.Unusable[0]
			if u.Path != r.file || u.Line != r.skipped || u.Reason == "" {
				t.Errorf("Unusable = %+v, want {Path:%s Line:%s} with a reason", u, r.file, r.skipped)
			}

			wantComponents, wantSkipped := 1, 0
			if r.counted {
				wantComponents, wantSkipped = 2, 1
			}
			if stats.Cataloged != 1 {
				t.Errorf("Cataloged = %d, want 1", stats.Cataloged)
			}
			if stats.SkippedNoVersion != wantSkipped {
				t.Errorf("SkippedNoVersion = %d, want %d", stats.SkippedNoVersion, wantSkipped)
			}
			if stats.Components != wantComponents {
				t.Errorf("Components = %d, want %d", stats.Components, wantComponents)
			}
			if stats.SkippedNoPURL != 0 || stats.SkippedUnsupportedEcosystem != 0 {
				t.Errorf("stats = %+v, want only SkippedNoVersion to carry a skip", stats)
			}
		})
	}
}
