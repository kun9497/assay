// A multi-descriptor key needs no parsing at all: every descriptor on it
// resolves to the one package the entry's own resolution: names.
func TestParse_BerryMultiDescriptorKeyIsOneEntry(t *testing.T) {
	path := write(t, berryHeader+`"a@npm:^7.0.0, a@npm:^7.10.4":
  version: 7.10.4
  resolution: "a@npm:7.10.4"
`)
	pkgs, stats, _, err := Parse(path)
	if err != nil {
		t.Fatalf("Parse: %v", err)
	}
	if len(pkgs) != 1 || pkgs[0].Name != "a" || pkgs[0].Version != "7.10.4" {
		t.Fatalf("pkgs = %+v, want a@7.10.4 once", pkgs)
	}
	if stats.Components != 1 {
		t.Errorf("Components = %d, want 1 - one entry, however many descriptors its key lists", stats.Components)
	}
}

// A document containing a genuine duplicate YAML key must still parse (the
// whole reason this reads via yaml.Node rather than a map decode) and dedupe
// to one package rather than emitting it twice.
func TestParse_BerryDuplicateKeyStillParsesAndDedupes(t *testing.T) {
	path := write(t, berryHeader+`"@types/qs@npm:6.9.4":
  version: 6.9.4
  resolution: "@types/qs@npm:6.9.4"

"@types/qs@npm:6.9.4":
  version: 6.9.4
  resolution: "@types/qs@npm:6.9.4"
`)
	pkgs, stats, _, err := Parse(path)
	if err != nil {
		t.Fatalf("Parse: %v — a duplicate key must not fail the whole document", err)
	}
	if len(pkgs) != 1 || pkgs[0].Name != "@types/qs" || pkgs[0].Version != "6.9.4" {
		t.Fatalf("pkgs = %+v, want @types/qs@6.9.4 exactly once", pkgs)
	}
	if stats.Components != 1 || stats.Cataloged != 1 {
		t.Errorf("stats = %+v, want the duplicate absorbed silently", stats)
	}
}

// Two different versions of the same name are both real packages - dedupe is
// on name@version, never on the bare name.
func TestParse_BerryTwoVersionsOfSameNameBothKept(t *testing.T) {
	path := write(t, berryHeader+`"async@npm:^3.2.0":
  version: 3.2.6
  resolution: "async@npm:3.2.6"

"async@npm:^0.9.0":
  version: 0.9.2
  resolution: "async@npm:0.9.2"
`)
	pkgs, _, _, err := Parse(path)
	if err != nil {
		t.Fatalf("Parse: %v", err)
	}
	got := map[string]bool{}
	for _, p := range pkgs {
		got[p.Name+"@"+p.Version] = true
	}
	if !got["async@3.2.6"] || !got["async@0.9.2"] {
		t.Fatalf("pkgs = %+v, want both async@3.2.6 and async@0.9.2", pkgs)
	}
}

