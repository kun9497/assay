// berryHeader is the __metadata block every fixture below needs so
// classifyDialect routes to parseBerry rather than the v1 scanner or
// ErrUnknownDialect.
const berryHeader = `# This file is generated by running "yarn install" inside your project.
__metadata:
  version: 8
  cacheKey: 10

`

// TestParse_BerrySplitResolution transcribes splitResolution's own rows from
// D103's adversarial table directly - the boundary-scanning rule (first "@"
// followed by lowercase letters then ":") is exactly what a patch:
// resolution's nested locator would break under the "split on the last @"
// rule syft uses instead.
func TestParse_BerrySplitResolution(t *testing.T) {
	cases := []struct {
		res      string
		wantName string
		wantProt string
		wantOK   bool
	}{
		{"lodash@npm:4.17.21", "lodash", "npm", true},
		{"@babel/cli@npm:7.27.1", "@babel/cli", "npm", true},
		{"typescript@patch:typescript@npm%3A5.9.2#builtin<compat/typescript>::version=5.9.2&hash=5786d5",
			"typescript", "patch", true},
		{"@yarnpkg/cli@workspace:packages/yarnpkg-cli", "@yarnpkg/cli", "workspace", true},
		{"pem@https://github.com/dexus/pem.git#commit=71dae334abcd", "pem", "https", true},
		{"$repo-utils@link:./scripts/repo-utils::locator=root-workspace%40workspace%3A.",
			"$repo-utils", "link", true},
		{"gatsby-plugin-algolia-docsearch@portal:./plugins/algolia-docsearch::locator=site%40workspace%3A.",
			"gatsby-plugin-algolia-docsearch", "portal", true},
		{"JSONStream@npm:1.3.5", "JSONStream", "npm", true},
		{"resolve@npm:1.9.0", "resolve", "npm", true},
		// No protocol boundary at all: a bare name, or a URL-encoded "npm%3A"
		// that must NOT satisfy the literal-":" requirement.
		{"just-a-name", "", "", false},
		{"typescript@npm%3A5.9.2", "", "", false},
	}
	for _, tc := range cases {
		t.Run(tc.res, func(t *testing.T) {
			name, proto, _, ok := splitResolution(tc.res)
			if ok != tc.wantOK || name != tc.wantName || proto != tc.wantProt {
				t.Errorf("splitResolution(%q) = (%q, %q, _, %v), want (%q, %q, _, %v)",
					tc.res, name, proto, ok, tc.wantName, tc.wantProt, tc.wantOK)
			}
		})
	}
}

func TestParse_BerryLodash(t *testing.T) {
	path := write(t, berryHeader+`"lodash@npm:^4.17.0":
  version: 4.17.21
  resolution: "lodash@npm:4.17.21"
`)
	pkgs, _, _, err := Parse(path)
	if err != nil {
		t.Fatalf("Parse: %v", err)
	}
	if len(pkgs) != 1 || pkgs[0].Name != "lodash" || pkgs[0].Version != "4.17.21" {
		t.Fatalf("pkgs = %+v, want lodash@4.17.21", pkgs)
	}
}

