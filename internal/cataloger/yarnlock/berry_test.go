// A patch: entry is silently absorbed - no Skipped entry, no Stats bump -
// because the npm: twin it patches already reports the same name and
// version. Silence here is deliberate (see parseBerry's own comment): naming
// every patch: entry would just repeat what the twin already says.
func TestParse_BerryPatchIsSilentWhenTheNpmTwinExists(t *testing.T) {
	path := write(t, berryHeader+`"typescript@npm:5.9.2":
  version: 5.9.2
  resolution: "typescript@npm:5.9.2"

"typescript@patch:typescript@npm%3A5.9.2#builtin<compat/typescript>::version=5.9.2&hash=5786d5":
  version: 5.9.2
  resolution: "typescript@patch:typescript@npm%3A5.9.2#builtin<compat/typescript>::version=5.9.2&hash=5786d5"
`)
	pkgs, stats, skipped, err := Parse(path)
	if err != nil {
		t.Fatalf("Parse: %v", err)
	}
	if len(pkgs) != 1 || pkgs[0].Name != "typescript" || pkgs[0].Version != "5.9.2" {
		t.Fatalf("pkgs = %+v, want typescript@5.9.2 alone", pkgs)
	}
	if stats.Components != 1 || stats.Cataloged != 1 {
		t.Errorf("stats = %+v, want the patch entry to leave no trace at all", stats)
	}
	if len(skipped) != 0 {
		t.Errorf("skipped = %+v, want none - the patch: entry is silent", skipped)
	}
}

