// A resolution with no recognizable protocol boundary at all is malformed,
// not silently dropped.
func TestParse_BerryUnrecognizableResolutionIsMalformed(t *testing.T) {
	path := write(t, berryHeader+`"broken-entry@npm:^1.0.0":
  version: 1.0.0
  resolution: "not-a-valid-resolution-string"
`)
	pkgs, stats, skipped, err := Parse(path)
	if err != nil {
		t.Fatalf("Parse: %v", err)
	}
	if len(pkgs) != 0 {
		t.Fatalf("pkgs = %+v, want none", pkgs)
	}
	if stats.Components != 1 || stats.SkippedNoPURL != 1 {
		t.Errorf("stats = %+v, want 1 component skipped as no-purl", stats)
	}
	if len(skipped) != 1 {
		t.Fatalf("skipped = %+v, want one entry", skipped)
	}
	if !strings.Contains(skipped[0].Reason, "protocol boundary") {
		t.Errorf("Reason = %q, want it to name the missing protocol boundary", skipped[0].Reason)
	}
}

